print("Первое число: " )
a = int(input())
print("Второе число: ")
b = int(input())
print("В частности у нас есть действия, а именно:")
print("Сложение: +, Вычитание: -")
print("Умножение: *, Деление: /")
print("Возведение числа в степень: **, Остаток от деления: %")
print("Введите знак, чтобы выполнить желаемое действие (+, -, /, *, **, %) ")
znak = input()
if znak == "+":
    print("Итог:", a + b)
elif znak == "-":
    print("Итог:", a - b)
elif znak == "*":
    print("Итог:", a * b)
elif znak == "/":
    print("Итог:", a / b)
elif znak == "**":
    print("Итог:", a ** b)
elif znak == "%":
    print("Итог:", a % b)
else:
    print("ОШИБКА ТАКОГО ДЕЙСТВИЯ НЕ СУЩЕСТВУЕТ")

